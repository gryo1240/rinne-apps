/* ============================================================
   taxonomy.js － ジャンルの分類と色
   ---------- 大分類 ----------
   地図のピンは「どの2色も隣り合いうる」ので、色は all-pairs で検証する必要がある。
   dataviz の validate_palette.js で測ったところ、4色は全パターンで判定に落ちた
   （4色目がどの色相でも、色覚特性のシミュレーションで既存の3色のどれかと近づく）。
   そのため**ピンの色は3つの大分類だけ**にして、細かい8ジャンルは
   チップ・タグ・ポップアップの**文字**で示している。
   採用値（light / dark）は all-pairs で全項目 PASS 済み。数値は HANDOFF-dev.md 第5章。
   ============================================================ */
window.AGM = window.AGM || {};

(function(){
"use strict";

var T = AGM.taxonomy = {};

T.BIG_OF = {
  "和食":"ごはん", "洋食":"ごはん", "中華・ラーメン":"ごはん",
  "焼肉・鉄板焼き":"ごはん", "多国籍":"ごはん",
  "カフェ・喫茶":"カフェ・甘いもの", "スイーツ・パン":"カフェ・甘いもの",
  "居酒屋・バー":"居酒屋・バー"
};
T.BIG_ORDER = ["ごはん","カフェ・甘いもの","居酒屋・バー"];
T.BIG_VAR   = { "ごはん":"--c-meal", "カフェ・甘いもの":"--c-cafe", "居酒屋・バー":"--c-bar" };

/* リストを「種類ごとにまとめる」ときの並び順 */
T.GROUP_ORDER = ["ごはん － 和食","ごはん － 洋食","ごはん － 中華・ラーメン",
  "ごはん － 焼肉・鉄板焼き","ごはん － 多国籍","カフェ・甘いもの","居酒屋・バー"];

/* ジャンルチップの並び順（データに無いものは後ろへ） */
T.GENRE_ORDER = ["和食","洋食","中華・ラーメン","焼肉・鉄板焼き","多国籍",
  "カフェ・喫茶","スイーツ・パン","居酒屋・バー"];

/* 設備の長い名前を短く出す。絞り込みチップとタグで使う */
T.SVC_SHORT = {
  "お子様連れ対応可能":"子連れOK", "キッズメニュー有":"キッズメニュー",
  "テイクアウトメニュー有":"テイクアウト", "全席完全禁煙":"全席禁煙",
  "無料Wi-Fi利用可能":"Wi-Fi", "席予約可能":"予約できる", "宅配可能":"宅配",
  "野菜を120g以上使用したメニュー有":"野菜たっぷり"
};

/* 検索でよく使われる言い換え。「ラーメン」「パン」などで引けるようにする */
T.SYNONYM = {
  "らーめん":"ラーメン", "ラーメン":"中華・ラーメン", "中華":"中華・ラーメン",
  "喫茶":"カフェ・喫茶", "カフェ":"カフェ・喫茶", "モーニング":"カフェ・喫茶",
  "パン":"スイーツ・パン", "ケーキ":"スイーツ・パン", "スイーツ":"スイーツ・パン",
  "居酒屋":"居酒屋・バー", "バー":"居酒屋・バー", "焼肉":"焼肉・鉄板焼き",
  "寿司":"和食", "そば":"和食", "うなぎ":"和食", "定食":"和食",
  "イタリアン":"洋食", "パスタ":"洋食", "カレー":"多国籍"
};

T.bigOf = function(shop){ return T.BIG_OF[shop.genre] || "その他"; };

/* CSS変数の実際の値を読む。ダークモードでも同じ関数で正しい色が取れる。
   JS 側に色をベタ書きしないこと。 */
T.color = function(big){
  var v = T.BIG_VAR[big];
  if(!v) return "#8a837a";
  var c = getComputedStyle(document.documentElement).getPropertyValue(v).trim();
  return c || "#8a837a";
};

T.soft = function(hex){
  if(!hex || hex.length!==7) return "rgba(128,128,128,.16)";
  var r=parseInt(hex.slice(1,3),16), g=parseInt(hex.slice(3,5),16), b=parseInt(hex.slice(5,7),16);
  if(isNaN(r)||isNaN(g)||isNaN(b)) return "rgba(128,128,128,.16)";
  return "rgba("+r+","+g+","+b+",.16)";
};

})();
